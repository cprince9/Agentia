import io
import os
import uuid
import zipfile
from datetime import datetime
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, status
from fastapi.responses import PlainTextResponse, StreamingResponse
from pydantic import BaseModel
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from ...db import crud
from ...db.models import Artifact
from ..dependencies import get_db

router = APIRouter(tags=["artifacts"])


class ArtifactMetaResponse(BaseModel):
    id: str
    session_id: str
    file_path: str
    file_type: str
    size_bytes: Optional[int] = None
    created_at: datetime


@router.get("/sessions/{session_id}/artifacts", response_model=List[ArtifactMetaResponse])
async def list_artifacts(
    session_id: str,
    db: AsyncSession = Depends(get_db),
):
    """
    List all generated artifacts and metadata for a specific session.
    """
    try:
        sid = uuid.UUID(session_id)
    except ValueError:
        raise HTTPException(status_code=400, detail="Invalid session UUID")

    artifacts = await crud.get_artifacts(db=db, session_id=sid)
    return [
        ArtifactMetaResponse(
            id=str(a.id),
            session_id=str(a.session_id),
            file_path=a.file_path,
            file_type=a.file_type,
            size_bytes=a.size_bytes,
            created_at=a.created_at,
        )
        for a in artifacts
    ]


@router.get("/artifacts/{artifact_id}/content", response_class=PlainTextResponse)
async def get_artifact_content(
    artifact_id: str,
    db: AsyncSession = Depends(get_db),
):
    """
    Retrieve raw text content of an individual artifact by its ID.
    """
    try:
        aid = uuid.UUID(artifact_id)
    except ValueError:
        raise HTTPException(status_code=400, detail="Invalid artifact UUID")

    stmt = select(Artifact).where(Artifact.id == aid)
    result = await db.execute(stmt)
    artifact = result.scalar_one_or_none()

    if not artifact:
        raise HTTPException(status_code=404, detail="Artifact not found")

    # Check local filesystem or return simulated content based on path
    if os.path.exists(artifact.file_path):
        with open(artifact.file_path, "r", encoding="utf-8", errors="replace") as f:
            return f.read()

    return f"# Artifact: {artifact.file_path}\n# Type: {artifact.file_type}\n# Generated by MASDS\n"


@router.get("/sessions/{session_id}/artifacts/download")
async def download_artifacts_zip(
    session_id: str,
    db: AsyncSession = Depends(get_db),
):
    """
    Package all session artifacts into a zip archive and stream to the client.
    """
    try:
        sid = uuid.UUID(session_id)
    except ValueError:
        raise HTTPException(status_code=400, detail="Invalid session UUID")

    artifacts = await crud.get_artifacts(db=db, session_id=sid)
    if not artifacts:
        raise HTTPException(status_code=404, detail="No artifacts found for this session")

    zip_buffer = io.BytesIO()
    with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        for a in artifacts:
            clean_path = a.file_path.lstrip("/\\")
            content = ""
            if os.path.exists(a.file_path):
                try:
                    with open(a.file_path, "r", encoding="utf-8", errors="replace") as f:
                        content = f.read()
                except Exception:
                    content = f"# Could not read {a.file_path}"
            else:
                content = f"# File: {a.file_path}\n# Auto-generated artifact for session {session_id}\n"

            zf.writestr(clean_path, content)

    zip_buffer.seek(0)
    zip_filename = f"masds_session_{session_id[:8]}_artifacts.zip"

    return StreamingResponse(
        zip_buffer,
        media_type="application/zip",
        headers={
            "Content-Disposition": f'attachment; filename="{zip_filename}"',
            "Cache-Control": "no-cache",
        },
    )
